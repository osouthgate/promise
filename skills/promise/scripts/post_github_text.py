#!/usr/bin/env python3
"""Post an issue or pull request body only when its promise block passes the lint,
then read back what GitHub stored.

    python3 post_github_text.py --kind pr --body-file BODY.md --number 12 [--changed rows.json]
    python3 post_github_text.py --kind pr --body-file BODY.md --new --title "…" [--base main] [--draft]
    python3 post_github_text.py --kind issue --body-file BODY.md --number 7
    python3 post_github_text.py --kind issue --body-file BODY.md --new --title "…"
    python3 post_github_text.py --kind pr --body-file BODY.md --verify 12

It runs ``lint_github_text.py`` on the file first (with ``--changed`` for a pull
request, and ``--cwd``), and posts nothing while the lint reports an error. It posts
with ``gh`` (``gh pr edit|create``, ``gh issue edit|create``, ``--body-file``), which
holds its own credentials: this script reads none. With no ``gh`` it says so (exit 2):
post through the host's GitHub tool, whose hook lints the same way
(``hooks/guard_github_text.py``), then run ``--verify``.

After posting, and alone with ``--verify <number>``, it reads the stored body back
(``gh … view --json body``) and compares it to the file. GitHub, or a tool on the way,
can change a body: a footer appended by the agent's GitHub integration (a ``---`` line
and a "Generated by" line) is known and ignored; anything else is a finding, and links
wrapped in backticks are named, since they no longer render as links. It lints the
stored body too. Exit 0 posted (or verified) and the same, 1 the lint failed or the
stored body differs, 2 refused (no ``gh``, a bad flag, a file that cannot be read).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from typing import List, Optional

sys.dont_write_bytecode = True
_SCRIPTS_DIR = os.path.dirname(os.path.abspath(__file__))
LINT = os.path.join(_SCRIPTS_DIR, "lint_github_text.py")
FOOTER_RE = re.compile(r"(?:\n+---)?\n+_?(?:🤖\s*)?Generated (?:by|with) \[Claude Code\]\([^)]*\)_?\s*$")
WRAPPED_LINK_RE = re.compile(r"`+\s*(\[[^\]\n]+\]\([^)\n]+\))\s*`+")


def lint(path: str, kind: str, cwd: str, changed: Optional[str], as_json: bool = False) -> subprocess.CompletedProcess:
    cmd = [sys.executable, LINT, "--kind", kind, path, "--cwd", cwd] + (["--json"] if as_json else [])
    if changed and kind == "pr":
        cmd += ["--changed", changed]
    return subprocess.run(cmd, capture_output=True, text=True)


def gh(args: List[str], cwd: str) -> subprocess.CompletedProcess:
    return subprocess.run(["gh", *args], capture_output=True, text=True, cwd=cwd, stdin=subprocess.DEVNULL,
                          timeout=120)


def normalise(text: str) -> str:
    return text.replace("\r\n", "\n").strip()


def compare(sent: str, stored: str) -> List[str]:
    """What GitHub stored that the file did not say, besides the known footer."""
    sent, stored = normalise(sent), normalise(stored)
    stored = FOOTER_RE.sub("", stored).strip()
    sent = FOOTER_RE.sub("", sent).strip()
    if stored == sent:
        return []
    problems = []
    wrapped = WRAPPED_LINK_RE.findall(stored)
    if wrapped:
        problems.append(f"{len(wrapped)} link(s) came back wrapped in backticks, so they no longer render as "
                        f"links (first: {wrapped[0][:80]}); post the links in another form "
                        "(references/github-text.md § Row links)")
        unwrapped = WRAPPED_LINK_RE.sub(lambda m: m.group(1), stored)
        if unwrapped == sent:
            return problems
    sent_lines, stored_lines = sent.splitlines(), stored.splitlines()
    for n, (a, b) in enumerate(zip(sent_lines, stored_lines), 1):
        if a != b:
            problems.append(f"line {n} differs: sent {a[:60]!r}, stored {b[:60]!r}")
            break
    if len(sent_lines) != len(stored_lines):
        problems.append(f"sent {len(sent_lines)} lines, GitHub stored {len(stored_lines)}")
    return problems


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--kind", choices=("pr", "issue"), required=True)
    ap.add_argument("--body-file", required=True)
    target = ap.add_mutually_exclusive_group(required=True)
    target.add_argument("--number", type=int, help="the pull request or issue to update")
    target.add_argument("--new", action="store_true", help="open a new one")
    target.add_argument("--verify", type=int, metavar="NUMBER", help="post nothing: read back and compare")
    ap.add_argument("--title", help="the title, for --new")
    ap.add_argument("--base", help="the base branch, for a new pull request")
    ap.add_argument("--head", help="the pushed branch, for a new pull request (gh cannot ask which)")
    ap.add_argument("--draft", action="store_true", help="open a new pull request as a draft")
    ap.add_argument("--changed", help="changed_rows.py --json output, for the pull request lint")
    ap.add_argument("--cwd", default=os.getcwd())
    args = ap.parse_args(argv)
    cwd = os.path.abspath(args.cwd)
    args.body_file = os.path.abspath(args.body_file)  # gh runs in --cwd; the file is the caller's
    try:
        with open(args.body_file, "r", encoding="utf-8-sig") as fh:
            sent = fh.read()
    except (OSError, ValueError) as exc:
        print(f"post_github_text.py: {exc}", file=sys.stderr)
        return 2
    if args.new and not (args.title and args.title.strip()):
        print("post_github_text.py: --new needs --title", file=sys.stderr)
        return 2

    if args.verify is None:
        result = lint(args.body_file, args.kind, cwd, args.changed)
        sys.stdout.write(result.stdout)
        if result.returncode != 0:
            sys.stderr.write(result.stderr)
            print("post_github_text.py: the lint failed; nothing was posted", file=sys.stderr)
            return 1 if result.returncode == 1 else 2
    if shutil.which("gh") is None:
        print("post_github_text.py: no gh on PATH. The lint passed: post the file through the host's GitHub "
              "tool, then run this with --verify <number>", file=sys.stderr)
        return 2

    noun = "pr" if args.kind == "pr" else "issue"
    number = args.verify or args.number
    if args.verify is None:
        if args.new:
            cmd = [noun, "create", "--title", args.title, "--body-file", args.body_file]
            if args.kind == "pr":
                cmd += (["--base", args.base] if args.base else []) + (["--head", args.head] if args.head else [])
                cmd += ["--draft"] if args.draft else []
        else:
            cmd = [noun, "edit", str(args.number), "--body-file", args.body_file]
        done = gh(cmd, cwd)
        if done.returncode != 0:
            print(f"post_github_text.py: gh {' '.join(cmd[:2])} failed: {done.stderr.strip()[:300]}", file=sys.stderr)
            return 1
        if args.new:
            m = re.search(r"/(?:pull|issues)/(\d+)", done.stdout)
            number = int(m.group(1)) if m else None
        print(done.stdout.strip() or f"posted {noun} {number}")
    if number is None:
        print("post_github_text.py: posted, but gh printed no number to read back; run --verify <number>")
        return 0
    view = gh([noun, "view", str(number), "--json", "body"], cwd)
    if view.returncode != 0:
        print(f"post_github_text.py: could not read {noun} {number} back: {view.stderr.strip()[:200]}",
              file=sys.stderr)
        return 1
    stored = json.loads(view.stdout or "{}").get("body") or ""
    problems = compare(sent, stored)
    with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as fh:
        fh.write(stored)
        stored_path = fh.name
    try:
        again = lint(stored_path, args.kind, cwd, args.changed, as_json=True)
    finally:
        os.unlink(stored_path)
    if again.returncode == 1:
        try:
            first = next(f for f in json.loads(again.stdout)["findings"] if f.get("severity") == "error")
            said = f"line {first.get('line') or 1}: {first['rule']} {first['message']}"
        except (ValueError, KeyError, StopIteration):
            said = "see lint_github_text.py on the stored body"
        problems.append("the body GitHub stored fails the lint: " + said[:200])
    if problems:
        print(f"{noun} {number}: GitHub stored a different body:")
        for p in problems:
            print(f"  {p}")
        return 1
    print(f"{noun} {number}: GitHub stored the body as sent")
    return 0


if __name__ == "__main__":
    sys.exit(main())
